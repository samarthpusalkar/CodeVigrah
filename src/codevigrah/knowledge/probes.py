"""Shortcoming probes: heuristics that flag likely weak spots, with why they are hard to fix."""

# kind=absent: flagged when pattern NOT found anywhere. kind=present: flagged when found (>=min).
PROBES = [
    # --- all domains
    dict(
        id='bare-except',
        domains=['all'],
        kind='present',
        pattern=r'^\s*except\s*:|catch\s*\(\s*\w*\s*\)\s*\{\s*\}|except\s+Exception\s*:\s*pass',
        langs=['Python', 'JavaScript', 'TypeScript', 'Java'],
        title='Swallowed errors',
        why='Errors are caught and discarded, so failures become silent wrong behaviour.',
        hard='Fixing means deciding for each site what the right recovery is. Tests rarely cover failure paths, so you cannot rely on them to show what breaks when errors start surfacing.',
    ),
    dict(
        id='secrets',
        domains=['all'],
        kind='present',
        pattern=r'(api[_-]?key|secret|passwd|password|token)\s*[=:]\s*[\'"][A-Za-z0-9_\-/+]{16,}[\'"]',
        excl_roles=['test', 'docs'],
        title='Possible hard-coded secret',
        why='Credentials in source persist in git history forever.',
        hard='Removing the line is not enough: the secret must be rotated and history cleaned; consumers must switch to injected config.',
    ),
    dict(
        id='eval',
        domains=['all'],
        kind='present',
        pattern=r'(?<![\w.])(eval|exec)\(|new Function\(|os\.system\(|shell=True',
        excl_roles=['test', 'docs'],
        title='Dynamic code / shell execution',
        why='Executes strings as code or commands, a common injection route if any input reaches them.',
        hard='Replacing it requires understanding all inputs that can flow in; the dynamic behaviour is often relied on by features.',
    ),
    dict(
        id='todo',
        domains=['all'],
        kind='present',
        pattern=r'\b(TODO|FIXME|HACK|XXX)\b',
        min=15,
        title='Large backlog of TODO/FIXME markers',
        why='Known gaps recorded in code comments; they cluster where the design is under strain.',
        hard='Each marker is a deferred decision; fixing one often reveals the reason it was deferred (a missing abstraction).',
    ),
    dict(
        id='no-logging',
        domains=['all'],
        kind='absent',
        pattern=r'(\blogging\b|\blogger\b|\bwinston\b|\bpino\b|\bzap\.|\bslog\b|\btracing::|\blog\.(info|debug|warn|error)|\blog4j|\bslf4j|console\.(error|warn))',
        title='No structured logging visible',
        why='Without logs you cannot diagnose production failures.',
        hard='Adding observability late means choosing event names and context (request ids) and threading them through every layer.',
    ),
    # --- backend
    dict(
        id='no-timeouts',
        domains=['network'],
        kind='absent',
        pattern=r'(timeout|deadline|set_read_timeout|SetDeadline|settimeout)',
        title='No network timeouts visible',
        why='A silent peer can hold a connection (and its memory/task) forever.',
        hard='Timeouts must be added at every await/read point, and each one needs a decision about what happens next (retry, close, report).',
    ),
    dict(
        id='no-frame-limit',
        domains=['network'],
        kind='absent',
        pattern=r'(max_?(frame|message|packet|len|length|size)|MAX_(FRAME|MESSAGE|LEN|SIZE|BUF)|LengthDelimited|with_max|max_length)',
        title='No message size limit visible',
        why="A peer can send an endless 'message' and exhaust memory.",
        hard='The limit belongs in the framing layer that every message passes through; choosing a value can break legitimate large messages.',
    ),
    dict(
        id='no-auth',
        domains=['backend', 'network'],
        kind='absent',
        pattern=r'(jwt|oauth|passport|authenticate|bearer|login_required|@PreAuthorize|authorization|auth_required|Depends\(.*(user|auth))',
        title='No authentication layer visible',
        why='No code recognisably authenticates callers.',
        hard='Auth has to wrap every entry point and every data query (ownership filters). Adding it later means auditing every handler and every query; missing one is a vulnerability.',
    ),
    dict(
        id='no-validation',
        domains=['backend'],
        kind='absent',
        pattern=r'(pydantic|marshmallow|\bzod\b|\bjoi\b|\byup\b|class-validator|serializers\.|@Valid|jsonschema|wtforms|cerberus|validator\.)',
        title='No input-validation library visible',
        why='Request data is trusted or checked by hand.',
        hard='Validation belongs at the boundary, but handlers already consume raw data in many shapes; tightening it changes accepted inputs and may break existing clients.',
    ),
    dict(
        id='no-ratelimit',
        domains=['backend'],
        kind='absent',
        pattern=r'(rate.?limit|throttl|limiter|slowapi|bucket4j)',
        title='No rate limiting visible',
        why='A client can overwhelm the service.',
        hard='Needs shared state (a counter store) across instances and a decision on the key (user, IP, token); behaviour under limit exhaustion must be defined for every endpoint.',
    ),
    dict(
        id='sql-concat',
        domains=['backend', 'database'],
        kind='present',
        pattern=r'(execute|query|raw)\(\s*(f["\']|["\'][^"\']*["\']\s*\+|`[^`]*\$\{|["\'][^"\']*["\']\s*%\s*\w)',
        excl_roles=['test'],
        title='SQL built by string concatenation',
        why='Classic SQL-injection vector and quoting bug source.',
        hard='Converting to parameters requires understanding every dynamic part (identifiers cannot be parameterised) and retesting each query.',
    ),
    dict(
        id='http-timeout',
        domains=['backend', 'cli', 'ml', 'library'],
        kind='present',
        pattern=r'requests\.(get|post|put|delete|patch)\((?![^)\n]*timeout)',
        langs=['Python'],
        excl_roles=['test'],
        title='HTTP calls without timeout',
        why='A hung upstream hangs your worker forever.',
        hard='Choosing a timeout is a product decision per call; retries multiply load; callers must handle the new failure.',
    ),
    dict(
        id='no-health',
        domains=['backend'],
        kind='absent',
        pattern=r'(/health|healthz|readyz|livez|/ping|/status\b)',
        title='No health-check endpoint',
        why='Orchestrators and load balancers cannot tell if the service is alive.',
        hard='Easy to add, but a meaningful readiness check must know which dependencies are essential; a wrong one causes cascading restarts.',
    ),
    dict(
        id='no-migrations',
        domains=['backend'],
        kind='special',
        title='Data models without migrations',
        why='Schema is defined in code but there is no visible migration history.',
        hard='Schema changes in production then become manual and error-prone; introducing migrations means baselining the existing schema first.',
    ),
    # --- frontend
    dict(
        id='no-a11y',
        domains=['frontend'],
        kind='absent',
        pattern=r'(aria-|\brole=|\balt=|jsx-a11y|axe-core|tabindex)',
        title='No accessibility attributes visible',
        why='Screen-reader and keyboard users likely cannot use the UI.',
        hard="Accessibility lives in every component's markup and focus handling; there is no single file to patch and it must be retested across flows.",
    ),
    dict(
        id='no-errorboundary',
        domains=['frontend'],
        kind='absent',
        pattern=r'(ErrorBoundary|componentDidCatch|onErrorCaptured|errorElement|error\.(tsx|jsx|vue|svelte)|onerror)',
        title='No UI error boundary visible',
        why='A render exception can blank the whole page.',
        hard='Needs a decision on granularity (page vs widget) and a fallback UI per boundary, plus error reporting.',
    ),
    dict(
        id='raw-html',
        domains=['frontend'],
        kind='present',
        pattern=r'(dangerouslySetInnerHTML|v-html|\.innerHTML\s*=|\{@html)',
        excl_roles=['test'],
        title='Raw HTML injection points',
        why='XSS risk if any input is untrusted.',
        hard='Requires a sanitiser at the right point and tracing the data origin for each use.',
    ),
    dict(
        id='no-ts',
        domains=['frontend', 'backend'],
        kind='special',
        title='JavaScript without static types',
        why='Shape mismatches are found at runtime.',
        hard='Migrating incrementally means types for shared data first; `any` can make it look done while guaranteeing nothing.',
    ),
    # --- cli
    dict(
        id='no-exitcodes',
        domains=['cli'],
        kind='absent',
        pattern=r'(sys\.exit|os\.Exit|process\.exit|exit\(|std::process::exit|ExitCode)',
        title='No explicit exit codes',
        why='Scripts cannot detect failure.',
        hard='Exit-code semantics are a public contract; assigning them requires classifying every failure.',
    ),
    dict(
        id='no-signal',
        domains=['cli'],
        kind='absent',
        pattern=r'(signal\.|SIGINT|SIGTERM|KeyboardInterrupt|ctrl_c|os/signal)',
        title='No interrupt handling',
        why='Ctrl-C can leave partial files or locks behind.',
        hard='Cleanup must be safe at any point in a long operation; usually forces restructuring into resumable steps.',
    ),
    dict(
        id='no-tty',
        domains=['cli'],
        kind='absent',
        pattern=r'(isatty|isTTY|NO_COLOR|is_terminal|IsTerminal|supports-color)',
        title='No TTY / colour detection',
        why='Escape codes can pollute piped output and logs.',
        hard='Every printing site must route through a single output abstraction; scattered prints must be found and replaced.',
    ),
    # --- database engine
    dict(
        id='no-recovery',
        domains=['database'],
        kind='absent',
        pattern=r'(\bwal\b|write.?ahead|journal|checkpoint|\brecover)',
        title='No crash-recovery mechanism visible',
        why='A crash can leave data inconsistent.',
        hard='Recovery must be designed into every write path (log before data, fsync ordering); bolting it on means rewriting writes.',
    ),
    dict(
        id='no-concurrency',
        domains=['database'],
        kind='absent',
        pattern=r'(mvcc|\block\b|latch|mutex|isolation|RwLock|sync\.)',
        title='No concurrency control visible',
        why='Concurrent clients can corrupt each other.',
        hard='Concurrency touches every shared structure; correctness depends on global invariants, not local edits.',
    ),
    dict(
        id='no-fsync',
        domains=['database'],
        kind='absent',
        pattern=r'(fsync|sync_all|sync_data|fdatasync|FlushFileBuffers|\.sync\()',
        title='No explicit fsync',
        why='Acknowledged writes can be lost on power failure.',
        hard='fsync has a large performance cost, so adding it forces batching/group-commit designs.',
    ),
    # --- library
    dict(
        id='no-changelog',
        domains=['library'],
        kind='special',
        title='No changelog / release notes',
        why='Consumers cannot see what changed between versions.',
        hard='Reconstructing history after the fact is laborious; needs a release discipline.',
    ),
]
